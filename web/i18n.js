let language = "vi";
try { if (globalThis.localStorage?.getItem("language") === "en") language = "en"; } catch { /* Storage may be disabled. */ }
const parameters = new WeakMap();
export function locale() { return language === "en" ? "en-US" : "vi-VN"; }
export function t(key, ...args) {
  const template = messages[key]?.[language === "en" ? 1 : 0] ?? key;
  return template.replace(/\{(\d+)\}/g, (_, index) => {
    const value = args[index];
    return typeof value === "number" ? value.toLocaleString(locale(), {maximumFractionDigits: 2}) : String(value ?? "");
  });
}
// Only explicitly bound UI labels are translated; input values and API data are untouched.
export function text(element, value) {
  const descriptor = Array.isArray(value) ? value : Object.entries(messages).find(([, pair]) => pair.includes(value))?.slice(0, 1);
  if (descriptor) {
    const [key, ...args] = descriptor;
    element.dataset.i18n = key;
    parameters.set(element, args);
    element.textContent = t(key, ...args);
  } else {
    delete element.dataset.i18n;
    parameters.delete(element);
    element.textContent = value;
  }
}
export function translate(root = document) {
  for (const element of root.querySelectorAll("[data-i18n]"))
    element.textContent = t(element.dataset.i18n, ...(parameters.get(element) || []));
  for (const name of ["placeholder", "aria-label", "title"])
    for (const element of root.querySelectorAll(`[data-i18n-${name}]`))
      element.setAttribute(name, t(element.getAttribute(`data-i18n-${name}`)));
}
export function wireLanguage(render) {
  const select = document.querySelector("#language");
  function apply() {
    document.documentElement.lang = language;
    select.value = language;
    translate();
  }
  select.onchange = () => {
    language = select.value === "en" ? "en" : "vi";
    try { localStorage.setItem("language", language); } catch { /* Keep switching usable without storage. */ }
    apply();
    render();
  };
  apply();
}
