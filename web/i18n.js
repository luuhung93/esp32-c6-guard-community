export function apiError(error) {
  if (error?.code) return t(errorKeys[error.code] || "theRequestWasNotApplied");
  const key = Object.keys(messages).find(key => messages[key].includes(error?.message));
  return key ? t(key) : error?.message || t("theRequestWasNotApplied");
}
